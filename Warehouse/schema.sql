-- ==============================================================================
-- Скрипт инициализации физической схемы базы данных "WarehouseDB" (Складской учет)
-- СУБД: Microsoft SQL Server (T-SQL)
-- Архитектура: Нормализованная OLTP-схема (3NF) с B-Tree индексацией
-- ==============================================================================

-- Создание новой базы данных с параметрами по умолчанию
CREATE DATABASE WarehouseDB;
GO

-- Переключение контекста выполнения на созданную БД
USE WarehouseDB;
GO

-- ------------------------------------------------------------------------------
-- 1. Создание служебной таблицы пользователей для системы авторизации (RBAC)
-- Обоснование: Изоляция учетных данных от бизнес-логики.
-- ------------------------------------------------------------------------------
CREATE TABLE Users (
    Id INT IDENTITY(1,1) PRIMARY KEY, -- Суррогатный первичный автоинкрементный ключ
    Login NVARCHAR(50) NOT NULL UNIQUE, -- Уникальный логин, предотвращающий дубли учетных записей
    PasswordHash NVARCHAR(256) NOT NULL, -- Хранилище необратимого криптографического слепка SHA-256
    Role NVARCHAR(20) NOT NULL DEFAULT 'User' -- Роль по умолчанию (Принцип наименьших привилегий)
);
GO

-- ------------------------------------------------------------------------------
-- 2. Создание нормализованного центрального справочника номенклатуры (Products)
-- Обоснование: Приведение к 3NF, устранение дублирования названий товаров в заказах.
-- ------------------------------------------------------------------------------
CREATE TABLE Products (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL, -- Unicode-строка для поддержки национальных алфавитов
    Category NVARCHAR(50) NOT NULL, -- Товарная группа для аналитической агрегации
    BasePrice DECIMAL(18, 2) NOT NULL CHECK (BasePrice >= 0) -- Точный математический тип (без округлений)
);
GO

-- ------------------------------------------------------------------------------
-- 3. Создание справочника контрагентов (Suppliers)
-- Обоснование: Управление цепочками поставок (Supply Chain), хранение юридической информации.
-- ------------------------------------------------------------------------------
CREATE TABLE Suppliers (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL,
    ContactInfo NVARCHAR(150),
    Address NVARCHAR(255)
);
GO

-- ------------------------------------------------------------------------------
-- 4. Создание топологического справочника складских локаций (StorageCells)
-- Обоснование: Поддержка концепции распределенных складов (multi-location optimization).
-- ------------------------------------------------------------------------------
CREATE TABLE StorageCells (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(50) NOT NULL, -- Буквенно-цифровое обозначение стеллажа/ячейки (например, "A-12")
    Capacity INT NULL -- Физическая вместимость зоны (задел под логику WMS-ячеистого хранения)
);
GO

-- ------------------------------------------------------------------------------
-- 5. Создание таблицы реестра заказов (Orders)
-- Обоснование: Документы-основания, легализующие транзакции физического движения.
-- ------------------------------------------------------------------------------
CREATE TABLE Orders (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    SupplierId INT NULL FOREIGN KEY REFERENCES Suppliers(Id), -- Внешний ключ, обеспечивающий ссылочную целостность
    OrderDate DATETIME NOT NULL DEFAULT GETDATE(), -- Автоматическая фиксация системного времени
    Status NVARCHAR(50) NOT NULL DEFAULT 'В обработке' -- Статусная модель документа
);
GO

-- ------------------------------------------------------------------------------
-- 6. Создание центральной ассоциативной сущности транзакций (Movements)
-- Обоснование: Разрешение связи "Многие-ко-Многим" (M:N) между заказами, товарами и складами.
-- Это ядро OLTP-системы, фиксирующее каждый факт движения материальных ценностей.
-- ------------------------------------------------------------------------------
CREATE TABLE Movements (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    ProductId INT NOT NULL FOREIGN KEY REFERENCES Products(Id), -- Запрет удаления товара, если есть движения
    CellId INT NOT NULL FOREIGN KEY REFERENCES StorageCells(Id), -- Фиксация локации изменения остатка
    OrderId INT NULL FOREIGN KEY REFERENCES Orders(Id),
    MovementType NVARCHAR(20) NOT NULL CHECK (MovementType IN ('Поступление', 'Отгрузка')), -- Жесткий доменный контроль
    Quantity INT NOT NULL CHECK (Quantity > 0), -- Защита от ввода отрицательного или нулевого оборота
    TotalCost DECIMAL(18, 2) NOT NULL CHECK (TotalCost >= 0), -- Фиксация исторической стоимости партии
    MovementDate DATETIME NOT NULL DEFAULT GETDATE()
);
GO

-- ------------------------------------------------------------------------------
-- 7. Разработка стратегии индексирования (B-Tree Data Structures)
-- Обоснование: Предотвращение эффекта полного сканирования таблиц (Table Scan) 
-- при выполнении тяжелых операций объединения (JOIN) и агрегации в DWH-отчетах.
-- ------------------------------------------------------------------------------
-- Индекс по товару многократно ускорит запросы вычисления текущих остатков
CREATE NONCLUSTERED INDEX IX_Movements_ProductId ON Movements(ProductId);
GO
-- Индекс по ячейкам ускорит инвентаризацию конкретных складских зон
CREATE NONCLUSTERED INDEX IX_Movements_CellId ON Movements(CellId);
GO
-- Индекс по дате критически важен для аудита за период и фильтрации WHERE
CREATE NONCLUSTERED INDEX IX_Movements_MovementDate ON Movements(MovementDate);
GO



